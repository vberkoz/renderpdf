func injectPrintCSS(html string) string {
	if strings.Contains(html, "__RENDERPDF_INJECTED__") {
		return html
	}

	const css = `<!-- __RENDERPDF_INJECTED__ -->
<style id="__lambda_print_fix__">
@media print {
  * {
    -webkit-print-color-adjust: exact !important;
    print-color-adjust: exact !important;
    forced-color-adjust: none !important;
  }
  thead {
    display: table-header-group !important;
  }
  tfoot {
    display: table-row-group !important;
  }
  tr,
  .signature, .signatures, .signature-block, .signature-row,
  .totals-area, .totals-table, .grand-total, .summary-row,
  .avoid-break, [data-avoid-break],
  figure, pre, blockquote {
    break-inside: avoid !important;
    page-break-inside: avoid !important;
  }
  h1, h2, h3, h4, h5, h6 {
    break-after: avoid !important;
    page-break-after: avoid !important;
  }
  p, li {
    orphans: 3;
    widows: 3;
  }
}
</style>
`

	if strings.Contains(html, "</head>") {
		return strings.Replace(html, "</head>", css+"</head>", 1)
	}

	return css + html
}
