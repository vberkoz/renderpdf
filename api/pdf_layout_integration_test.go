func requireChromeForIntegrationTest(t *testing.T) {
	t.Helper()
	if _, err := prepareChrome(); err != nil {
		t.Skipf("Chrome not available (%v) - run inside API Docker container", err)
	}
}

func assertPDFNoDefaultFooter(t *testing.T, pdfBytes []byte) {
	t.Helper()
	if bytes.Contains(pdfBytes, []byte("Generated by RenderPDF")) {
		t.Fatalf("raw PDF bytes unexpectedly contain legacy footer")
	}
	conf := model.NewDefaultConfiguration()
	conf.ValidationMode = model.ValidationRelaxed
	err := api.ExtractContent(bytes.NewReader(pdfBytes), nil, func(r io.Reader, pageNr int) error {
		content, readErr := io.ReadAll(r)
		if readErr != nil {
			return readErr
		}
		if bytes.Contains(content, []byte("Generated by RenderPDF")) {
			t.Fatalf("page %d extracted content unexpectedly contains legacy footer", pageNr)
		}
		return nil
	}, conf)
	if err != nil {
		t.Fatalf("pdfcpu ExtractContent failed: %v", err)
	}
}

func assertLetterLandscapeDims(t *testing.T, sourceName string, pdfBytes []byte) {
	t.Helper()
	if !bytes.HasPrefix(pdfBytes, []byte("%PDF")) {
		t.Fatalf("%s did not produce valid PDF header", sourceName)
	}
	conf := model.NewDefaultConfiguration()
	conf.ValidationMode = model.ValidationRelaxed
	dims, err := api.PageDims(bytes.NewReader(pdfBytes), conf)
	if err != nil {
		t.Fatalf("%s PageDims failed: %v", sourceName, err)
	}
	if len(dims) == 0 {
		t.Fatalf("%s produced 0 pages", sourceName)
	}
	if math.Abs(dims[0].Width-792.0) > 2.0 || math.Abs(dims[0].Height-612.0) > 2.0 {
		t.Fatalf("%s page[0] dims = (%.2f x %.2f pt), want Letter landscape (~792 x 612 pt)", sourceName, dims[0].Width, dims[0].Height)
	}
}

func TestAllSourceTypesPDFDimensions(t *testing.T) {
	requireChromeForIntegrationTest(t)
	t.Setenv("DEFAULT_DISPLAY_HEADER_FOOTER", "")

	prevLoader := sourceDefinitionLoader
	prevTplFactory := templateStoreFactory
	t.Cleanup(func() {
		sourceDefinitionLoader = prevLoader
		templateStoreFactory = prevTplFactory
	})

	falseVal := false
	sourceDefinitionLoader = func(_ context.Context, ownerID, sourceID string) (canonicalRenderRequest, error) {
		return canonicalRenderRequest{
			Version: "1",
			Source:  canonicalRenderSource{Type: "html", Content: "<style>@page { size: A4 portrait; }</style><h1>{{title}}</h1>"},
			Data:    map[string]any{"title": "Stored"},
			Options: documentRenderOptions{Format: "A4", Margin: "20mm", Landscape: &falseVal},
		}, nil
	}

	store := &memoryTemplateAPIStore{
		templates: map[string]Template{
			"customer-a/tpl-dim": {
				ID:      "tpl-dim",
				Name:    "Dimension Template",
				Type:    TemplateType("invoice"),
				HTML:    "<style>@page { size: A4 portrait; }</style><h1>{{title}}</h1>",
				OwnerID: "customer-a",
			},
		},
	}

	ctx := context.Background()
	optsJSON := `"options":{"format":"Letter","margin":"12mm","landscape":true}`

	// 1. html (plain)
	t.Run("html", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"html","content":"<style>@page { size: A4 portrait; }</style><h1>HTML</h1>"},`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		var req Request
		if err := json.Unmarshal([]byte(norm.Body), &req); err != nil {
			t.Fatal(err)
		}
		html := transformBarcodes(rewriteTfoot(injectPrintCSS(req.HTML)))
		pdfBytes, err := generatePDFWithOptions(ctx, html, *req.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "html", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})

	// 2. markdown
	t.Run("markdown", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"markdown","content":"# Markdown Report\n\nBody"},"data":{},`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		docHTML, docReq, err := resolveDocumentRenderHTML(norm.Body)
		if err != nil {
			t.Fatal(err)
		}
		pdfBytes, err := generateDocumentPDFWithOptions(ctx, docHTML, docReq.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "markdown", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})

	// 3. template
	t.Run("template", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"template","templateId":"tpl-dim","variables":{"title":"Template"}},`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		resolvedHTML, tplReq, err := resolveTemplateRenderHTML(ctx, store, "customer-a", norm.Body)
		if err != nil {
			t.Fatal(err)
		}
		html := transformBarcodes(rewriteTfoot(injectPrintCSS(resolvedHTML)))
		pdfBytes, err := generatePDFWithOptions(ctx, html, *tplReq.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "template", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})

	// 4. url (using allowed file:// path under /tmp/renderpdf-package-*)
	t.Run("url", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"url","url":"https://example.com"},`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		var req URLRequest
		if err := json.Unmarshal([]byte(norm.Body), &req); err != nil {
			t.Fatal(err)
		}
		dir, err := os.MkdirTemp("/tmp", "renderpdf-package-urltest-")
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = os.RemoveAll(dir) })
		entryPath := filepath.Join(dir, "index.html")
		if err := os.WriteFile(entryPath, []byte(`<!doctype html><html><head><style>@page { size: A4 portrait; }</style></head><body><h1>URL</h1></body></html>`), 0600); err != nil {
			t.Fatal(err)
		}
		fileURL := (&url.URL{Scheme: "file", Path: entryPath}).String()
		pdfBytes, err := generatePDFURLWithDocumentOptions(ctx, fileURL, *req.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "url", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})

	// 5. upload (in-memory ZIP -> extract + injectPackageCSP)
	t.Run("upload", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"upload","uploadId":"0f8fad5b-d9cb-469f-a165-70867728950e","entrypoint":"index.html"},`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		var req packageRenderRequest
		if err := json.Unmarshal([]byte(norm.Body), &req); err != nil {
			t.Fatal(err)
		}
		var zipBuf bytes.Buffer
		zw := zip.NewWriter(&zipBuf)
		f, err := zw.Create("index.html")
		if err != nil {
			t.Fatal(err)
		}
		if _, err := f.Write([]byte(`<!doctype html><html><head><style>@page { size: A4 portrait; }</style></head><body><h1>Upload</h1></body></html>`)); err != nil {
			t.Fatal(err)
		}
		if err := zw.Close(); err != nil {
			t.Fatal(err)
		}
		dir, err := os.MkdirTemp("/tmp", "renderpdf-package-uploadtest-")
		if err != nil {
			t.Fatal(err)
		}
		t.Cleanup(func() { _ = os.RemoveAll(dir) })
		zr, err := zip.NewReader(bytes.NewReader(zipBuf.Bytes()), int64(zipBuf.Len()))
		if err != nil {
			t.Fatal(err)
		}
		entryPath := filepath.Join(dir, "index.html")
		rc, err := zr.File[0].Open()
		if err != nil {
			t.Fatal(err)
		}
		htmlBytes, err := io.ReadAll(rc)
		_ = rc.Close()
		if err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(entryPath, htmlBytes, 0600); err != nil {
			t.Fatal(err)
		}
		if err := injectPackageCSP(entryPath); err != nil {
			t.Fatal(err)
		}
		fileURL := (&url.URL{Scheme: "file", Path: entryPath}).String()
		pdfBytes, err := generatePDFURLWithDocumentOptions(ctx, fileURL, *req.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "upload", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})

	// 6. stored (merges Letter/landscape over saved A4/portrait)
	t.Run("stored", func(t *testing.T) {
		norm, err := normalizeCanonicalRenderRequestWithOwner(ctx, `{"version":"1","source":{"type":"stored","id":"src-dim"},"label":"Stored Test",`+optsJSON+`}`, "customer-a")
		if err != nil {
			t.Fatal(err)
		}
		docHTML, docReq, err := resolveDocumentRenderHTML(norm.Body)
		if err != nil {
			t.Fatal(err)
		}
		pdfBytes, err := generateDocumentPDFWithOptions(ctx, docHTML, docReq.Options)
		if err != nil {
			t.Fatal(err)
		}
		assertLetterLandscapeDims(t, "stored", pdfBytes)
		assertPDFNoDefaultFooter(t, pdfBytes)
	})
}

func TestMultiPageTablePagination(t *testing.T) {
	requireChromeForIntegrationTest(t)
	t.Setenv("DEFAULT_DISPLAY_HEADER_FOOTER", "")

	var rows strings.Builder
	for i := 1; i <= 120; i++ {
		fmt.Fprintf(&rows, `<tr style="height:28px;"><td>Row %d</td><td>Description %d</td></tr>`+"\n", i, i)
	}
	html := `<!doctype html><html><head><style>table{width:100%;border-collapse:collapse;}td,th{height:28px;padding:4px 8px;border:1px solid #ccc;}</style></head><body><table><thead><tr><th>ID</th><th>Item</th></tr></thead><tbody>` + rows.String() + `</tbody></table></body></html>`

	rendered := rewriteTfoot(injectPrintCSS(html))
	pdfBytes, err := generatePDFWithOptions(context.Background(), rendered, documentRenderOptions{
		Format: "A4",
		Margin: "18mm",
	})
	if err != nil {
		t.Fatalf("generatePDFWithOptions failed: %v", err)
	}

	conf := model.NewDefaultConfiguration()
	conf.ValidationMode = model.ValidationRelaxed
	pageCount, err := api.PageCount(bytes.NewReader(pdfBytes), conf)
	if err != nil {
		t.Fatalf("PageCount failed: %v", err)
	}
	if pageCount < 3 {
		t.Fatalf("pageCount = %d, want >= 3 so multi-page tbody splits cleanly across pages", pageCount)
	}
	assertPDFNoDefaultFooter(t, pdfBytes)
}
